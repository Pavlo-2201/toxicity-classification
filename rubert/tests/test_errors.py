@pytest.mark.parametrize("word", NEUTRAL)
def test_neutral_words_are_not_markers(word):
    text = f"Мне кажется, {word} — вполне обычное слово в этом контексте"
    c = categorize(text, oov_share=0.0)
    assert not c["obscene"] and not c["insult_lexicon"] and c["no_explicit_markers"], word


@pytest.mark.parametrize("word", OBSCENE)
def test_obscene_forms(word):
    assert has_obscene(f"Ну ты {word.upper()}!"), word


@pytest.mark.parametrize("word", INSULT)
def test_insult_forms(word):
    assert has_insult(f"Ну ты {word.capitalize()}!"), word
    assert not categorize(f"Ну ты {word}!", oov_share=0.0)["no_explicit_markers"]


def test_categories():
    c = categorize("Да пошёл ты на хуй", oov_share=0.0)
    assert c["short"] and c["obscene"] and not c["no_explicit_markers"]
    c = categorize("Уважаемый, вы, кажется, не вполне понимаете, о чём пишете в этом треде", oov_share=0.0)
    assert not c["short"] and c["no_explicit_markers"]
    assert categorize("ну ты д.ебил", oov_share=0.0)["obfuscation_or_typos"]
    assert categorize("какды чейто", oov_share=1.0)["obfuscation_or_typos"]
    assert not categorize("Небольшая заметка про погоду в городе", oov_share=0.0)["obscene"]
    assert not categorize("Плохо, что ожидать ответа приходится долго", oov_share=0.0)["insult_lexicon"]
